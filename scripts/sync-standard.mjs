/**
 * Regenerate the `preset-standard` override in the desktop profile from the
 * *installed* app.asar, then append the main-trim plugin row.
 *
 * Why copy instead of patching in place: a profile patch row overrides
 * `config.plugins` wholesale, so the override must carry every upstream row.
 * Re-run this after a DSH upgrade to pick up new built-in plugins.
 *
 * Usage: node scripts/sync-standard.mjs [--apply]
 */
import { readFileSync, writeFileSync, copyFileSync, existsSync } from 'node:fs';

const ASAR = 'D:/agant/dsh-desktop/resources/app.asar';
const ENTRY = 'dsh/node_modules/@deepseek-ai/dsh-web-app/presets/standard.patch.yml';
const PROFILE_PATCH = 'C:/Users/ASUS/.dsh/profiles/desktop/cordis.patch.yml';
const BEGIN = '# === main-trim BEGIN (generated by dsh-main-trim/scripts/sync-standard.mjs) ===';
const END = '# === main-trim END ===';
const EXTRA = `
      - id: main-trim
        name: 'dsh-main-trim/main-trim.mjs'`;

function readAsar(path) {
	const fd = readFileSync(path);
	const jsonLen = fd.readUInt32LE(12);
	const header = JSON.parse(fd.subarray(16, 16 + jsonLen).toString('utf8'));
	const dataStart = 8 + fd.readUInt32LE(4);
	const walk = (node, base) => {
		for (const [name, child] of Object.entries(node.files)) {
			const p = base ? `${base}/${name}` : name;
			if (child.files) {
				const hit = walk(child, p);
				if (hit) return hit;
			} else if (p === ENTRY) return child;
		}
	};
	const file = walk(header, '');
	if (!file) throw new Error(`entry not found in asar: ${ENTRY}`);
	const start = dataStart + Number(file.offset);
	return fd.subarray(start, start + file.size).toString('utf8');
}

const raw = readAsar(ASAR);
if (!raw.includes('id: preset-standard')) throw new Error('unexpected standard.patch.yml shape');
// The web-app bundle inserts this row. To *override* it from the profile we must
// emit a bare row with the same id: an `- insert:` block would append a second
// declaration, and duplicate preset ids fail to load.
const lines = raw.split('\n').filter((line) => !line.startsWith('#'));
const insertAt = lines.findIndex((line) => line.trim() === '- insert:');
if (insertAt < 0) throw new Error('unexpected standard.patch.yml shape: no insert row');
const source = lines
	.slice(insertAt + 1)
	.map((line) => (line.startsWith('    ') ? line.slice(4) : line))
	.join('\n')
	.trimEnd();
const block = `${BEGIN}\n${source}\n${EXTRA}\n${END}`;

const current = readFileSync(PROFILE_PATCH, 'utf8');
const start = current.indexOf(BEGIN);
const end = current.indexOf(END);
let next;
if (start >= 0 && end > start) {
	next = current.slice(0, start) + block + current.slice(end + END.length);
} else {
	next = `${current.trimEnd()}\n\n${block}\n`;
}

const added = (source.match(/^\s{4,}- id: /gm) ?? []).length;
console.log(`plugins in upstream standard preset: ${added}`);
if (next === current) {
	console.log('profile patch unchanged');
	process.exit(0);
}
if (!process.argv.includes('--apply')) {
	console.log('dry run; pass --apply to write');
	process.exit(0);
}
const backup = `${PROFILE_PATCH}.bak-maintrim-${new Date().toISOString().replace(/[:.]/g, '').slice(0, 15)}`;
copyFileSync(PROFILE_PATCH, backup);
writeFileSync(PROFILE_PATCH, next);
console.log(`wrote ${PROFILE_PATCH}\nbackup ${backup}`);
